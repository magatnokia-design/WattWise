#!/usr/bin/env node
/**
 * Turns the Dagitab logo into outlines and writes the files that draw it.
 *
 *   node scripts/generate-brand.js
 *
 * Writes:
 *   src/constants/brandMark.js     path data for the in-app <Wordmark>/<BrandMark>.
 *                                  Copy-rule: the web repo keeps a byte-identical
 *                                  copy at src/constants/brandMark.js.
 *   assets/brand/dagitab-logo.svg          full lockup with tagline, on white
 *   assets/brand/dagitab-logo-notag.svg    lockup without tagline
 *   assets/brand/dagitab-logo-white.svg    white lockup for green grounds
 *
 * Why outlines. The supplied full logo set "AGITAB" as live <text> in Arial.
 * That renders as Arial only where Arial is installed - Android has none, and
 * email clients and PDF tools substitute freely - so the wordmark would be a
 * different shape on every surface. Converting the glyphs to paths once makes
 * it a drawing, which renders identically everywhere and needs no font.
 *
 * Needs, at generation time only: Arial Bold / Bold Italic from C:\Windows\Fonts
 * and `fontkit`, borrowed from functions/node_modules (pdfkit depends on it).
 * The outputs are committed, so nothing at runtime or build time needs either.
 */

const fs = require('fs');
const path = require('path');
const { NAVY, WHITE, GREEN, LOGO, GRADIENT_SVG } = require('./brand-geometry');

const REPO_ROOT = path.resolve(__dirname, '..');

const loadFontkit = () => {
  for (const candidate of ['fontkit', path.join(REPO_ROOT, 'functions/node_modules/fontkit')]) {
    try {
      return require(candidate);
    } catch {
      // Try the next one.
    }
  }
  throw new Error('fontkit not found. Run `npm ci` in functions/ - pdfkit brings it in.');
};

const FONT_DIR = process.env.BRAND_FONT_DIR || 'C:/Windows/Fonts';
const fontkit = loadFontkit();
const wordFont = fontkit.openSync(path.join(FONT_DIR, 'arialbi.ttf'));
const tagFont = fontkit.openSync(path.join(FONT_DIR, 'arialbd.ttf'));

const round = (n) => Math.round(n * 10) / 10;

/** One SVG path for a run of text, glyphs positioned and flipped into SVG space. */
const outline = (font, { text, size, tracking }, x0, baseline) => {
  const k = size / font.unitsPerEm;
  const run = font.layout(text);
  let x = x0;
  const parts = [];
  run.glyphs.forEach((glyph, i) => {
    // Font units are y-up; SVG is y-down. Scale with a negative y, then move the
    // origin to this glyph's pen position on the baseline.
    const d = glyph.path.scale(k, -k).translate(x, baseline).toSVG();
    parts.push(d.replace(/-?\d+\.\d+|-?\d+/g, (n) => String(round(Number(n)))));
    x += run.positions[i].xAdvance * k + tracking;
  });
  return { d: parts.join(''), end: x - tracking };
};

const word = outline(wordFont, LOGO.word, LOGO.word.x, LOGO.word.baseline);

// Trim the supplier's 1600 artboard to the artwork: the word ends near x=1152,
// and the empty band to its right pushed the tagline (centred on 800) off
// centre under the logo.
const MARGIN = 50;
const left = MARGIN;
const right = Math.ceil(word.end) + 5;
const lockupCentre = (55 + word.end) / 2;

const tagRun = tagFont.layout(LOGO.tagline.text);
const tagWidth = tagRun.positions.reduce((sum, p) => sum + p.xAdvance, 0)
  * (LOGO.tagline.size / tagFont.unitsPerEm)
  + LOGO.tagline.tracking * (LOGO.tagline.text.length - 1);
const tagline = outline(tagFont, LOGO.tagline, lockupCentre - tagWidth / 2, LOGO.tagline.baseline);

// Vertical extent of the D (y 55..355), plus a hair so antialiasing is not cut.
const top = 50;
const markBottom = 360;
const taglineBottom = 410;

const viewBox = (bottom) => `${left} ${top} ${right - left} ${bottom - top}`;

// --- src/constants/brandMark.js ----------------------------------------------
const moduleSource = `/**
 * Dagitab logo outlines. GENERATED by scripts/generate-brand.js - do not edit.
 *
 * Copy-rule: the web repo keeps a byte-identical copy at the same path. Re-run
 * the generator in the app repo and copy this file across; never edit either.
 *
 * Coordinates are the supplier's logo artboard, trimmed to the artwork. The D
 * fills with the brand gradient (or white on a green ground); the bolt is cut
 * from it in white (or green); the word is navy (or white).
 */
export const BRAND_VIEWBOX = '${viewBox(markBottom)}';

// The D alone, for square marks: x 55..355, y 55..355.
export const BRAND_MARK_VIEWBOX = '50 50 310 310';

export const BRAND_D_PATH = '${LOGO.d}';

export const BRAND_BOLT_PATH = '${LOGO.bolt}';

export const BRAND_WORD_PATH = '${word.d}';

// Width / height of BRAND_VIEWBOX, so a caller sizing by height can reserve the
// right width before the SVG lays out.
export const BRAND_ASPECT = ${Math.round(((right - left) / (markBottom - top)) * 1000) / 1000};

export const BRAND_GRADIENT = { from: '#50D52B', to: '#008D43' };
`;

fs.writeFileSync(path.join(REPO_ROOT, 'src/constants/brandMark.js'), moduleSource);

// --- assets/brand/*.svg ------------------------------------------------------
const lockup = ({ textFill, dFill, boltFill, withTagline }) => {
  const bottom = withTagline ? taglineBottom : markBottom;
  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox(bottom)}" `
    + `width="${right - left}" height="${bottom - top}" role="img" aria-label="Dagitab">`
    + `<defs>${GRADIENT_SVG('dagitab-green')}</defs>`
    + `<path d="${LOGO.d}" fill="${dFill}"/>`
    + `<path d="${LOGO.bolt}" fill="${boltFill}"/>`
    + `<g fill="${textFill}"><path d="${word.d}"/>${withTagline ? `<path d="${tagline.d}"/>` : ''}</g>`
    + '</svg>\n';
};

const BRAND_DIR = path.join(REPO_ROOT, 'assets/brand');
fs.mkdirSync(BRAND_DIR, { recursive: true });

const files = {
  'dagitab-logo.svg': lockup({ textFill: NAVY, dFill: 'url(#dagitab-green)', boltFill: WHITE, withTagline: true }),
  'dagitab-logo-notag.svg': lockup({ textFill: NAVY, dFill: 'url(#dagitab-green)', boltFill: WHITE, withTagline: false }),
  'dagitab-logo-white.svg': lockup({ textFill: WHITE, dFill: WHITE, boltFill: GREEN, withTagline: true }),
};

for (const [name, svg] of Object.entries(files)) {
  fs.writeFileSync(path.join(BRAND_DIR, name), svg);
  console.log(`assets/brand/${name.padEnd(26)} ${(svg.length / 1024).toFixed(1)} KB`);
}
console.log(`src/constants/brandMark.js            ${(moduleSource.length / 1024).toFixed(1)} KB`);
console.log('\nCopy src/constants/brandMark.js to the web repo (copy-rule).');
